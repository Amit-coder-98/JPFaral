import {test,expect} from "@playwright/test";
const password="Example@JPfaral";
test("administrator creates a password-based staff account after matching confirmations",async({page})=>{
  await page.goto("/staff");await page.getByRole("button",{name:"Create user",exact:true}).click();
  const dialog=page.getByRole("dialog");
  await expect(dialog).not.toContainText(/invitation/i);
  await page.getByLabel("User name",{exact:false}).fill("Direct Staff");
  await page.getByLabel("Email address",{exact:false}).fill("direct@test.invalid");
  await page.getByLabel(/^Password/).fill(password);
  await page.getByLabel("Confirm password",{exact:false}).fill("Different@JPfaral");
  await dialog.getByRole("button",{name:"Create user",exact:true}).click();
  await expect(dialog.getByRole("alert")).toHaveText("Passwords do not match.");
  await page.getByLabel("Confirm password",{exact:false}).fill(password);
  await dialog.getByRole("button",{name:"Create user",exact:true}).click();
  await expect(dialog).toHaveCount(0);await expect(page.locator("tbody")).toContainText("Direct Staff");
  const row=page.locator("tbody tr").filter({hasText:"Direct Staff"});await expect(row).toContainText("Data Entry Staff");
  await expect(page.locator("main")).not.toContainText(password);
});
test("administrator can choose Admin; reopening and editing never retain creation passwords",async({page})=>{
  await page.goto("/staff");await page.getByRole("button",{name:"Create user",exact:true}).click();
  await page.getByLabel("User name",{exact:false}).fill("Direct Admin");
  await page.getByLabel("Email address",{exact:false}).fill("directadmin@test.invalid");
  await page.getByLabel(/^Password/).fill(password);await page.getByLabel("Confirm password",{exact:false}).fill(password);
  await page.getByLabel("User type").selectOption("Super Admin");
  await page.getByRole("dialog").getByRole("button",{name:"Create user",exact:true}).click();
  await expect(page.locator("tbody tr").filter({hasText:"Direct Admin"})).toContainText("Super Admin");
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.getByRole("button",{name:"Create user",exact:true}).click();
  await expect(page.getByLabel(/^Password/)).toHaveValue("");
  await page.getByLabel(/^Password/).fill(password);
  await page.getByRole("dialog").getByRole("button",{name:"Cancel",exact:true}).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.getByRole("button",{name:"Create user",exact:true}).click();await expect(page.getByLabel(/^Password/)).toHaveValue("");
  await page.getByRole("dialog").getByRole("button",{name:"Cancel",exact:true}).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.getByRole("button",{name:"Edit Direct Admin",exact:true}).click();
  await expect(page.getByLabel(/^Password/)).toHaveCount(0);
  await expect(page.getByRole("dialog").getByRole("button",{name:"Save changes",exact:true})).toBeVisible();
});
test("direct user form fits a phone with both role choices and masked password fields",async({page})=>{
  await page.setViewportSize({width:390,height:844});await page.goto("/staff");
  await page.getByRole("button",{name:"Create user",exact:true}).click();
  await expect(page.getByLabel("User type").locator("option")).toHaveText(["Data Entry Staff","Admin"]);
  await expect(page.getByLabel(/^Password/)).toHaveAttribute("type","password");
  await expect(page.getByLabel("Confirm password",{exact:false})).toHaveAttribute("type","password");
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  const bounds=await page.getByRole("dialog").boundingBox();expect(bounds!.width).toBeLessThanOrEqual(390);expect(bounds!.height).toBeLessThanOrEqual(844);
  await page.evaluate(()=>document.fonts.ready);await page.getByRole("dialog").screenshot({path:"test-results/create-user-phone.png"});
});
